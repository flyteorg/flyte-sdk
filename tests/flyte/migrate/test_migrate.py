def test_scheduled_launch_plan_becomes_trigger(tmp_path):
    result = migrate(
        tmp_path,
        """
        from datetime import timedelta
        from flytekit import CronSchedule, FixedRate, LaunchPlan, task, workflow

        @task
        def t(n: int) -> int:
            return n

        @workflow
        def wf(n: int, kickoff: str) -> int:
            return t(n=n)

        LaunchPlan.get_or_create(
            workflow=wf,
            name="nightly",
            schedule=CronSchedule(schedule="0 0 * * *", kickoff_time_input_arg="kickoff"),
            default_inputs={"n": 1},
        )
        hourly = LaunchPlan.create("hourly", wf, schedule=FixedRate(duration=timedelta(hours=1)))
        """,
    )
    code = flat(result.code)
    assert (
        '@env.task(entrypoint=True, triggers=(flyte.Trigger(name="nightly", automation=flyte.Cron("0 0 * * *"), '
        'inputs={"n": 1, \'kickoff\': flyte.TriggerTime}), flyte.Trigger(name="hourly", '
        "automation=flyte.FixedRate(interval_minutes=60)),))" in code
    )
    assert "LaunchPlan" not in result.code
    assert result.todos == []


