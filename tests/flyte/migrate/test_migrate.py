    code = flat(result.code)
    assert (
        'pipeline_sweep_env = flyte.TaskEnvironment(name="pipeline_sweep_env", image="sweep:1", '
        "depends_on=[pipeline_train_env])" in code
    )
    assert 'pipeline_env = flyte.TaskEnvironment(name="pipeline_env", depends_on=[pipeline_sweep_env])' in code
    assert code.index("pipeline_train_env = ") < code.index("pipeline_sweep_env = ") < code.index("pipeline_env = ")


