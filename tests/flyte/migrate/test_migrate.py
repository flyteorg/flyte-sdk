"""Tests for the flytekit (v1) -> flyte (v2) source migration behind `flyte migrate`."""

import importlib.util
import textwrap
from pathlib import Path

import pytest

pytest.importorskip("libcst")

import flyte
from flyte._migrate import MigrationError, migrate_file, output_path_for


@pytest.fixture(autouse=True)
def no_ruff(monkeypatch):
    """Assert on the converter's own output; ruff formatting is best-effort and version dependent."""
    monkeypatch.setattr("flyte._migrate._migrate._ruff_binary", lambda: None)


def migrate(tmp_path: Path, source: str, name: str = "pipeline.py", **kwargs):
    path = tmp_path / name
    path.write_text(textwrap.dedent(source))
    return migrate_file(path, **kwargs)


def flat(code: str) -> str:
    return " ".join(code.split())


# -- file handling ------------------------------------------------------------------------------------------------


def test_output_path_uses_suffix_next_to_source():
    assert output_path_for(Path("workflows/pipeline.py")) == Path("workflows/pipeline_v2.py")
    assert output_path_for(Path("train.py"), "_flyte2") == Path("train_flyte2.py")


@pytest.mark.parametrize("suffix", ["", "-v2", ".v2", "_v 2"])
def test_invalid_suffix_is_rejected(suffix):
    with pytest.raises(MigrationError, match="Invalid suffix"):
        output_path_for(Path("pipeline.py"), suffix)


def test_file_without_flytekit_has_nothing_to_migrate(tmp_path):
    result = migrate(tmp_path, "import os\n")
    assert result.status == "nothing_to_migrate"
    assert result.code == ""


def test_generated_file_has_nothing_to_migrate(tmp_path):
    first = migrate(tmp_path, "from flytekit import task\n\n@task\ndef t() -> int:\n    return 1\n")
    first.output_path.write_text(first.code)
    assert migrate_file(first.output_path).status == "nothing_to_migrate"


def test_syntax_error_raises(tmp_path):
    with pytest.raises(MigrationError, match=r"pipeline.py:2:\d+: syntax error"):
        migrate(tmp_path, "from flytekit import task\ndef (:\n")


def test_unknown_rule_raises(tmp_path):
    with pytest.raises(MigrationError, match="Unknown rule"):
        migrate(tmp_path, "from flytekit import task\n", rules=["nope"])


def test_header_and_todo_line_numbers(tmp_path):
    result = migrate(
        tmp_path,
        """
        from flytekit import conditional, task, workflow

        @task
        def t(x: int) -> int:
            return x

        @workflow
        def wf(x: int) -> int:
            return conditional("c").if_(x > 1).then(t(x=x)).else_().then(t(x=0))
        """,
    )
    lines = result.code.splitlines()
    assert lines[0].startswith("# Generated by `flyte migrate`")
    assert result.status == "converted_with_todos"
    assert [t.message for t in result.todos] == [
        "conditional() has no v2 equivalent; rewrite it as a Python if/elif/else inside the task"
    ]
    assert "TODO(flyte migrate)" in lines[result.todos[0].line - 1]


