# -- workflows ----------------------------------------------------------------------------------------------------


PARALLEL_WORKFLOW = """
from typing import List

from flytekit import map_task, task, workflow


@task
def load(n: int) -> int:
    return n


@task
def square(x: int) -> int:
    return x * x


@task
def total(a: int, b: int, squares: List[int]) -> int:
    return a + b + sum(squares)


@workflow
def wf(n: int = 3) -> int:
    \"\"\"Independent calls run concurrently in v1.\"\"\"
    a = load(n=n)
    b = load(n=n + 1).with_overrides(retries=2)
    squares = map_task(square, concurrency=2)(x=[1, 2, 3])
    return total(a=a, b=b, squares=squares)


@workflow
def linear(n: int = 2) -> int:
    a = load(n=n)
    return square(x=a)
"""


def test_independent_workflow_calls_are_gathered(tmp_path):
    result = migrate(tmp_path, PARALLEL_WORKFLOW, name="parallel_wf.py")
    code = flat(result.code)
    assert "async def wf(n: int = 3) -> int:" in code
    assert (
        "a, b, squares = await asyncio.gather(load.aio(n=n), load.override(retries=2).aio(n=n + 1), "
        "_collect(flyte.map.aio(square, [1, 2, 3], concurrency=2, return_exceptions=False)))" in code
    )
    assert "return await total.aio(a=a, b=b, squares=squares)" in code
    assert "async def _collect(results):" in code
    assert '"""Independent calls run concurrently in v1."""' in code
    # A chain of dependent calls keeps its synchronous form.
    assert "def linear(n: int = 2) -> int: a = load(n=n) return square(x=a)" in code
    assert result.todos == []


def test_migrated_workflows_run_locally(tmp_path, monkeypatch):
    result = migrate(tmp_path, PARALLEL_WORKFLOW, name="parallel_run_wf.py")
    result.output_path.write_text(result.code)
    monkeypatch.syspath_prepend(str(tmp_path))
    spec = importlib.util.spec_from_file_location("parallel_run_wf_v2", result.output_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    flyte.init()
    assert flyte.with_runcontext(mode="local").run(module.wf, n=3).outputs()[0] == 3 + 4 + 1 + 4 + 9
    assert flyte.with_runcontext(mode="local").run(module.linear, n=2).outputs()[0] == 4


def test_ordering_operator_is_respected(tmp_path):
    result = migrate(
        tmp_path,
        """
        from flytekit import task, workflow

        @task
        def a() -> None: ...

        @task
        def b() -> None: ...

        @task
        def c() -> None: ...

        @workflow
        def wf():
            x = a()
            y = b()
            z = c()
            x >> y
        """,
    )
    code = flat(result.code)
    assert "x, z = await asyncio.gather(a.aio(), c.aio()) y = await b.aio()" in code
    assert ">>" not in code


