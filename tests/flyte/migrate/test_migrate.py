def test_dynamic_map_task_and_overrides_in_sync_code(tmp_path):
    result = migrate(
        tmp_path,
        """
        import functools
        from flytekit import Resources, dynamic, map_task, task

        @task
        def add(x: int, y: int) -> int:
            return x + y

        @dynamic
        def fan(xs: list[int]) -> list[int]:
            doubled = map_task(functools.partial(add, y=1), min_success_ratio=0.5)(x=xs)
            add(x=1, y=2).with_overrides(requests=Resources(cpu="2"), node_name="n")
            return doubled
        """,
    )
    code = flat(result.code)
    assert "doubled = list(flyte.map(functools.partial(add, y=1), xs, return_exceptions=True))" in code
    assert 'add.override(resources=flyte.Resources(cpu="2"), short_name="n")(x=1, y=2)' in code
    assert [t.message for t in result.todos] == [
        "failed map items are returned as exceptions in v2; filter them to honor min_success(es/_ratio)"
    ]


